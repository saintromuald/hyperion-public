import struct, sys
def frame(f):
    hdr = struct.pack('<III', 0x50465848, f, 8) + struct.pack('<III', 128, 128, 2)
    units = [(1000,45,0,608,928,1250,0,0,0,11,1,1),(1001,41,0,672,1064,40,0,0,0,11,1,1),
             (1002,41,0,640,864,40,0,0,0,11,1,1),(1003,42,0,512,1224,200,0,0,0,11,1,1),
             (2000,106,1,2976,2976,1500,0,0,0,11,1,1),(2001,7,1,2912,3112,60,0,0,0,11,1,1),
             (2002,7,1,3112,2912,60,0,0,0,11,1,1),(2003,0,1,3272,3272,40,0,0,0,11,1,1)]
    for u in units:
        hdr += struct.pack('<IIIIIIIIIBBBB', u[0],u[1],u[2],u[3],u[4],u[5],u[6],u[7],u[8],u[9],u[10],0,0)
    for p in [(0,50,0,400,6,512,1024),(1,50,0,400,6,3072,3072)]:
        hdr += struct.pack('<IIIIIII', *p)
    return hdr
for f in range(30):
    sys.stdout.buffer.write(frame(f))
